type PartSeed = Omit<
  PlanPart,
  | 'blockedReason'
  | 'blockedBy'
  | 'expectedKind'
  | 'outcomeKind'
  | 'outcomeRef'
  | 'outcomeSummary'
  | 'touches'
  | 'atoms'
  | 'acceptanceMet'
  | 'size'
> &
  Partial<PlanPart> & {
    outsideScope?: string[];
    depth?: number;
  };

function demoPart(seed: PartSeed): PlanPartView {
  const part: PlanPart = {
    expectedKind: null,
    touches: [],
    atoms: [],
    acceptanceMet: [],
    size: null,
    outcomeKind: null,
    outcomeRef: null,
    outcomeSummary: null,
    blockedReason: null,
    blockedBy: null,
    ...seed,
  };
  return {
    ...part,
    depth: seed.depth ?? (part.dependsOn.length === 0 ? 0 : 1),
    acceptanceCriteria: (part.acceptance ?? '')
      .split('\n')
      .map((line) => line.replace(/^\s*(?:[-*+]|\d+[.)])\s+/, '').trim())
      .filter((text) => text !== '')
      .map((text) => ({ text, met: part.acceptanceMet.includes(text) })),
    outsideScope: seed.outsideScope ?? [],
  };
}

