const RENOVATE_BODY = [
  '| Package | Change |',
  '|---|---|',
  '| [dotenv](https://github.com/motdotla/dotenv) | `16.4.5` -> `17.0.1` |',
  '',
  '---',
  '',
  '### Release Notes',
  '',
  '<details><summary>motdotla/dotenv (dotenv)</summary>',
  '',
  '### [`v17.0.0`](https://github.com/motdotla/dotenv/releases/tag/v17.0.0)',
  '',
  '- Default `quiet` to false',
  '</details>',
  '',
  '---',
  '',
  '### Configuration',
  '',
  'This PR was generated by [Renovate Bot](https://github.com/renovatebot/renovate).',
].join('\n');

test('release notes are cut out of a Renovate body, and a Dependabot one', () => {
  const notes = releaseNotesInBody(RENOVATE_BODY);
  assert.ok(notes !== null);
  assert.ok(notes?.startsWith('### Release Notes'));
  assert.ok(notes.includes('Default `quiet` to false'));
  assert.ok(!notes.includes('Configuration'), 'the footer is not part of the notes');

  const dependabot = [
    'Bumps axios from 1.7.3 to 1.7.4.',
    '<details>',
    '<summary>Release notes</summary>',
    '<p>Fix a redirect bug</p>',
    '</details>',
    '<details>',
    '<summary>Commits</summary>',
    '<li>abc</li>',
    '</details>',
  ].join('\n');
  const found = releaseNotesInBody(dependabot);
  assert.ok(found !== null);
  assert.ok(found?.includes('Fix a redirect bug'));
  assert.ok(!found.includes('abc'), 'the commit list is left out');

  assert.equal(releaseNotesInBody('No notes here.'), null);
  assert.equal(releaseNotesInBody(null), null);
});

test('the source repository is the first github link that is no bot’s, and tags are tried in three shapes', () => {
  assert.deepEqual(sourceRepoInBody(RENOVATE_BODY), { owner: 'motdotla', repo: 'dotenv' });
  assert.equal(sourceRepoInBody('Generated by https://github.com/renovatebot/renovate'), null);
  assert.deepEqual(releaseTags('dotenv', '17.0.1'), ['v17.0.1', '17.0.1', 'dotenv@17.0.1']);
  assert.deepEqual(releaseTags(null, 'v2.0.0'), ['v2.0.0', '2.0.0']);
  assert.deepEqual(releaseTags('x', null), []);
});

